# Scenario: The quote page has a soft pink background
def test_pink_colours_set_via_inline_styles_not_external_css():
    """
    All new colours (pink background, deep-pink heading, pink-tinted shadow)
    must be set via inline styles in the shared page template.
    No external stylesheet, font link or script tag must be added.
    """
    html = _get_html()
    parser = _parse_html(html)

    for tag, attrs in parser.tags:
        if tag == "link":
            rel = attrs.get("rel", "").lower()
            assert "stylesheet" not in rel, (
                f"Found an external stylesheet link: {attrs}"
            )
            href = attrs.get("href", "")
            assert not href.startswith("http"), (
                f"Found an external <link> with remote href: {href}"
            )
        if tag == "style":
            # A <style> block means the colours are NOT in inline styles as required
            pytest.fail(
                "Found a <style> block; the specification requires inline styles only"
            )
        if tag == "script":
            assert "src" not in attrs, (
                f"Found an external script: {attrs}"
            )
