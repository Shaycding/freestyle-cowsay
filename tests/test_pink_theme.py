# Scenario: The quote page has a soft pink background
def test_page_background_is_soft_pink():
    """
    The page body background-color must be a soft pink.
    The existing blue-grey #f0f4f8 must no longer be used.
    We check that:
      - a background-color is present on the body
      - it is NOT the old blue-grey #f0f4f8
      - the colour is in the pink family (high R, low-to-mid G and B)
    """
    parser = _get_parser()
    bg = _extract_body_background_color(parser)

    assert bg is not None, (
        "No background-color found on the <body> element"
    )
    assert bg != "#f0f4f8", (
        f"Background is still the old blue-grey #f0f4f8; expected a soft pink"
    )

    # Verify it is pink-ish: R must be the dominant channel
    r, g, b = _hex_to_rgb(bg)
    assert r > g and r > b, (
        f"Background colour {bg} does not appear pink "
        f"(R={r:.2f}, G={g:.2f}, B={b:.2f}); R must be the dominant channel"
    )


# Scenario: The quote page has a soft pink background
def test_page_background_is_close_to_specification_pink():
    """
    The specification suggests #fde8ef as the target soft pink.
    We verify the background-color is very close to that value by checking
    it is in the range of light pinks: R >= 0.95, G in [0.85, 0.97],
    B in [0.85, 0.97], and B < G (cooler pinks).
    """
    parser = _get_parser()
    bg = _extract_body_background_color(parser)

    assert bg is not None, "No background-color found on the <body> element"

    r, g, b = _hex_to_rgb(bg)
    # Soft pink: very high red, moderate-high green, lower blue than green
    assert r >= 0.90, (
        f"Background {bg}: R={r:.3f} is too low for a soft pink (need >= 0.90)"
    )
    assert g >= 0.85, (
        f"Background {bg}: G={g:.3f} is too low for a soft pink (need >= 0.85)"
    )
    assert b >= 0.85, (
        f"Background {bg}: B={b:.3f} is too low for a soft pink (need >= 0.85)"
    )
    assert b < g, (
        f"Background {bg}: B={b:.3f} >= G={g:.3f}; pink tones have more green than blue"
    )


