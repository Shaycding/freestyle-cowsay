# Scenario: The custom text page uses the same pink shade
def test_same_template_serves_both_routes():
    """
    Both the / route and /:text (e.g. /hello) route call setCowsaySentence,
    so they share the same template and therefore the same pink background.
    We verify that both route handlers invoke setCowsaySentence.
    """
    source = _load_js_source()

    # There should be at least 3 references: 1 definition + ≥ 2 call sites
    calls = re.findall(r'setCowsaySentence\(', source)
    assert len(calls) >= 3, (
        f"Expected at least 3 references to setCowsaySentence "
        f"(1 definition + at least 2 route call sites), found {len(calls)}"
    )


# Scenario: The custom text page uses the same pink shade
def test_text_route_handler_calls_set_cowsay_sentence():
    """
    The /:text route handler must pass the request parameter to setCowsaySentence
    so that /hello renders 'hello' in the cow bubble. This ensures the pink
    background (from the shared template) is used on the custom text page.
    """
    source = _load_js_source()

    # The /:text route must exist and call setCowsaySentence with the text param
    assert re.search(r"app\.get\('/:text'", source) or re.search(r'app\.get\("/:text"', source), (
        "The /:text route must be defined"
    )
    # Within the /:text handler, setCowsaySentence must be called with the text
    text_route_match = re.search(
        r"app\.get\('/:text'.*?\}\);",
        source,
        re.DOTALL,
    ) or re.search(
        r'app\.get\("/:text".*?\}\);',
        source,
        re.DOTALL,
    )
    assert text_route_match, "Could not find the /:text route handler body"
    handler_body = text_route_match.group(0)
    assert "setCowsaySentence" in handler_body, (
        "The /:text handler must call setCowsaySentence to render the pink template"
    )


