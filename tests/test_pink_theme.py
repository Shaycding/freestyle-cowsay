"""
Tests for the soft pink theme applied to the Cow Say page.

These tests parse the HTML template embedded in cowsay/src/index.js and verify
that the setCowsaySentence function produces markup consistent with the
pink-theme specification. No running server or Node.js is required.

Strategy
--------
1. Extract the raw HTML template string from the JS source (substituting a
   known placeholder for the cowsay output so we can inspect the surrounding
   structure).
2. Parse the HTML with html.parser and apply assertions that check for the
   required pink colours and style attributes.
"""

import re
import html.parser
import pytest


# ---------------------------------------------------------------------------
# Helpers – re-use the same extraction strategy as test_cowsay_modern_ui.py
# ---------------------------------------------------------------------------

JS_PATH = "cowsay/src/index.js"


def _load_js_source() -> str:
    with open(JS_PATH, encoding="utf-8") as fh:
        return fh.read()


def _extract_html_template(source: str) -> str:
    """
    Return the *static* HTML generated by setCowsaySentence after replacing
    the cowsay.say(...) call with a fixed placeholder.
    """
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)

    # Replace the embedded JS expression ${cowsay.say({...})} with a placeholder
    template = re.sub(
        r'\$\{cowsay\.say\(\{[^}]*\}[^}]*\}\)',
        "__COW_OUTPUT__",
        template,
        flags=re.DOTALL,
    )
    # Remove any remaining ${...} interpolations
    template = re.sub(r'\$\{[^}]+\}', "__INTERPOLATION__", template)
    return template


class _CollectingParser(html.parser.HTMLParser):
    """Simple parser that records tags and their attrs in order."""

    def __init__(self):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []
        self.data_chunks: list[str] = []

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def handle_data(self, data):
        self.data_chunks.append(data)


def _parse_html(html_text: str) -> _CollectingParser:
    parser = _CollectingParser()
    parser.feed(html_text)
    return parser


def _combined_inline_styles(parser: _CollectingParser) -> str:
    """Return all inline style attribute values concatenated (lower-cased)."""
    parts = []
    for _tag, attrs in parser.tags:
        if "style" in attrs:
            parts.append(attrs["style"].lower())
    return " ".join(parts)


def _get_html() -> str:
    source = _load_js_source()
    return _extract_html_template(source)


def _get_parser() -> _CollectingParser:
    return _parse_html(_get_html())


# ---------------------------------------------------------------------------
# Colour helpers – WCAG 2.1 relative luminance and contrast ratio
# ---------------------------------------------------------------------------

def _hex_to_rgb(hex_color: str) -> tuple[float, float, float]:
    """Convert a hex colour like #fde8ef to (r, g, b) in [0, 1]."""
    h = hex_color.lstrip("#")
    assert len(h) == 6, f"Expected 6-char hex, got: {hex_color!r}"
    return (
        int(h[0:2], 16) / 255,
        int(h[2:4], 16) / 255,
        int(h[4:6], 16) / 255,
    )


def _linearise(c: float) -> float:
    if c <= 0.03928:
        return c / 12.92
    return ((c + 0.055) / 1.055) ** 2.4


def _relative_luminance(hex_color: str) -> float:
    r, g, b = _hex_to_rgb(hex_color)
    r, g, b = _linearise(r), _linearise(g), _linearise(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def _contrast_ratio(color1: str, color2: str) -> float:
    l1 = _relative_luminance(color1)
    l2 = _relative_luminance(color2)
    lighter = max(l1, l2)
    darker = min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)


def _extract_body_background_color(parser: _CollectingParser) -> str | None:
    """
    Extract the background-color value from the body element's inline style.
    Returns the hex-normalised value (e.g. '#fde8ef') or None if not found.
    """
    for tag, attrs in parser.tags:
        if tag == "body" and "style" in attrs:
            style = attrs["style"].lower()
            m = re.search(
                r'background(?:-color)?\s*:\s*(#[0-9a-f]{3,8})',
                style,
            )
            if m:
                return m.group(1)
    return None


def _extract_heading_color(parser: _CollectingParser) -> str | None:
    """
    Extract the color value from the first h1 element's inline style.
    Returns the hex value or None if not found.
    """
    for tag, attrs in parser.tags:
        if tag == "h1" and "style" in attrs:
            style = attrs["style"].lower()
            m = re.search(r'(?<![a-z-])color\s*:\s*(#[0-9a-f]{3,8})', style)
            if m:
                return m.group(1)
    return None


