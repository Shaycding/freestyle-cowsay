# Scenario: Grass is drawn under the cow on the custom text page
def test_grass_line_present_in_template():
    """
    The HTML template from setCowsaySentence must contain at least one
    line of ASCII grass characters. We look for a repeated grass character
    sequence in the raw template (after placeholder substitution).
    """
    html = _get_html()

    # A grass line is a run of repeated ASCII characters from the grass set
    # e.g. "^" repeated several times, or "/\\/\\/\\" etc.
    # We require at least 4 consecutive grass characters (no line breaks).
    grass_pattern = re.compile(
        r'[/\\|^vVwW\'`Y,.]{4,}',
        re.UNICODE,
    )
    assert grass_pattern.search(html), (
        "No grass line found in the rendered HTML template. "
        "Expected a repeated ASCII grass character sequence (e.g. ^^^^) "
        "directly below the cow drawing."
    )


# Scenario: Grass is drawn under the cow on the custom text page
def test_grass_is_shown_in_green_colour():
    """
    The grass must be shown in green via an inline style.
    Acceptable: color: green, color: #...green-ish hex, or any CSS that
    explicitly names a green colour on the element wrapping the grass.
    We accept 'color: green', 'color: #' followed by a green-ish value,
    or the word 'green' appearing in any inline style.
    """
    html = _get_html()

    # Collect all inline style attribute values from the template
    style_attrs = re.findall(r'style\s*=\s*["\']([^"\']*)["\']', html, re.IGNORECASE)

    def _is_green_color(color_str: str) -> bool:
        """Return True if the CSS color value is green (named or hex)."""
        c = color_str.strip().lower()
        if c == 'green':
            return True
        if c.startswith('#'):
            hex_val = c.lstrip('#')
            if len(hex_val) == 3:
                hex_val = ''.join(ch * 2 for ch in hex_val)
            if len(hex_val) == 6:
                r_ch = int(hex_val[0:2], 16)
                g_ch = int(hex_val[2:4], 16)
                b_ch = int(hex_val[4:6], 16)
                return g_ch > r_ch and g_ch > b_ch
        return False

    # Look for a style attribute that contains "color: <green-value>" where
    # "color" is a foreground color property (not background-color).
    # We use a negative lookbehind to exclude "background-color".
    foreground_color_re = re.compile(
        r'(?<![a-z-])color\s*:\s*([a-zA-Z]+|#[0-9a-fA-F]{3,6})',
        re.IGNORECASE,
    )
    found_green_style = False
    for style_val in style_attrs:
        for m in foreground_color_re.finditer(style_val):
            if _is_green_color(m.group(1)):
                found_green_style = True
                break
        if found_green_style:
            break

    assert found_green_style, (
        "No green color inline style found in the template. "
        "The grass must be shown in green using an inline style attribute "
        "(e.g., style=\"color: green\"). "
        "Existing style attributes found: " + str(style_attrs[:5])
    )


# Scenario: Grass is drawn under the cow on the custom text page
def test_grass_is_inside_pre_block():
    """
    The grass must be inside (or immediately adjacent/sibling to) the same
    monospace <pre> block as the cow drawing.

    We check that:
    - The grass line (a span or similar element with a green inline style,
      OR raw text) appears between the opening and closing of a <pre> block,
      OR
    - A <span style="color:green"> (or equivalent) appears in the raw HTML
      inside a <pre> context.

    Practically: the grass element or text must be within the first <pre>
    that contains the cow placeholder, OR there must be a green-styled span
    somewhere inside a <pre>.
    """
    html = _get_html()

    # Look for a <pre> block that contains both the cow placeholder and green styling
    # OR a <span style="color:green..."> that appears inside a <pre> block
    # We search the raw HTML string for a <span ...color.*green...> inside a <pre>...</pre>
    pre_blocks = re.findall(r'<pre[^>]*>.*?</pre>', html, re.DOTALL | re.IGNORECASE)

    # If there are no </pre> closing tags (self-contained), check raw template
    if not pre_blocks:
        # Fall back: just check that a green element exists somewhere in the template
        assert re.search(r'color\s*:\s*green', html, re.IGNORECASE), (
            "No green-coloured grass element found inside a <pre> block"
        )
        return

    # Check that at least one pre block contains a green-styled element
    found_green_in_pre = False
    for block in pre_blocks:
        if re.search(r'color\s*:\s*green', block, re.IGNORECASE):
            found_green_in_pre = True
            break
        # Or green hex inside style
        if re.search(r'color\s*:\s*#[0-9a-fA-F]{3,6}', block, re.IGNORECASE):
            color_match = re.search(
                r'color\s*:\s*#([0-9a-fA-F]{3,6})', block, re.IGNORECASE
            )
            if color_match:
                hex_val = color_match.group(1)
                if len(hex_val) == 3:
                    hex_val = ''.join(c * 2 for c in hex_val)
                r = int(hex_val[0:2], 16)
                g = int(hex_val[2:4], 16)
                b = int(hex_val[4:6], 16)
                if g >= r and g >= b:
                    found_green_in_pre = True
                    break

    assert found_green_in_pre, (
        "The grass (green-coloured element) must be inside the same <pre> "
        "monospace block as the cow drawing. No green colour found inside "
        "any <pre> block in the template."
    )


# Scenario: Grass is drawn under the cow on the custom text page
def test_grass_has_no_line_breaks():
    """
    The grass line must have no line breaks in it (it is a single line).
    We look for the green-styled element in the template and confirm its
    text content (the part between style tags or span tags) has no newlines.
    """
    html = _get_html()

    # Find span (or other element) with green color style
    span_match = re.search(
        r'<span[^>]*style\s*=\s*["\'][^"\']*color\s*:\s*'
        r'(?:green|#[0-9a-fA-F]{3,6})[^"\']*["\'][^>]*>(.*?)</span>',
        html,
        re.IGNORECASE | re.DOTALL,
    )
    if span_match:
        grass_content = span_match.group(1)
        assert '\n' not in grass_content, (
            "The grass line must not contain line breaks; "
            f"found newline in grass content: {repr(grass_content)}"
        )
    else:
        # If there's no span, the grass text may appear directly — just
        # confirm the pattern that looks like grass chars has no newline
        grass_pattern = re.compile(r'[/\\|^vVwW\'`Y,.]{4,}')
        m = grass_pattern.search(html)
        assert m, "No grass line found to check for line breaks"
        grass_text = m.group(0)
        assert '\n' not in grass_text, (
            "The grass line must not contain line breaks"
        )


