"""
Tests for the grass-under-the-cow feature.

These tests parse the HTML template embedded in cowsay/src/index.js and verify
that the setCowsaySentence function includes a line of green ASCII grass
directly below the cow's legs, inside the same monospace block.

No running server or Node.js is required – we inspect the JS source directly.
"""

import re
import html.parser
import pytest


# ---------------------------------------------------------------------------
# Helpers – reuse the same extraction strategy as the existing test files
# ---------------------------------------------------------------------------

JS_PATH = "cowsay/src/index.js"


def _load_js_source() -> str:
    with open(JS_PATH, encoding="utf-8") as fh:
        return fh.read()


def _extract_html_template(source: str) -> str:
    """
    Return the *static* HTML generated by setCowsaySentence after replacing
    the cowsay.say(...) call with a fixed placeholder so the surrounding
    markup can be examined.
    """
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)

    # Replace the embedded JS expression ${cowsay.say({...})} with a
    # recognisable placeholder that survives HTML parsing.
    template = re.sub(
        r'\$\{cowsay\.say\(\{[^}]*\}[^}]*\}\)',
        "__COW_OUTPUT__",
        template,
        flags=re.DOTALL,
    )
    # Remove any remaining ${...} interpolations
    template = re.sub(r'\$\{[^}]+\}', "__INTERPOLATION__", template)
    return template


class _CollectingParser(html.parser.HTMLParser):
    """Simple parser that records tags, their attrs, and text data in order."""

    def __init__(self):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []   # (tag, attrs_dict)
        self.data_chunks: list[str] = []
        # Track (tag, attrs) alongside data – store events in order
        self.events: list[tuple] = []  # ("start", tag, attrs) | ("data", text)

    def handle_starttag(self, tag, attrs):
        d = dict(attrs)
        self.tags.append((tag, d))
        self.events.append(("start", tag, d))

    def handle_data(self, data):
        self.data_chunks.append(data)
        self.events.append(("data", data))


def _parse_html(html_text: str) -> _CollectingParser:
    parser = _CollectingParser()
    parser.feed(html_text)
    return parser


def _get_html() -> str:
    source = _load_js_source()
    return _extract_html_template(source)


def _get_parser() -> _CollectingParser:
    return _parse_html(_get_html())


