# Scenario: Grass grows under the cow on the custom text page
def test_pre_block_contains_grass_after_cow():
    """
    The <pre> block must contain a grass line directly after the cow output
    (no blank line between them). We inspect the raw JS template to confirm
    there is a grass element / text following the cowsay.say expression.
    """
    source = _load_js_source()
    pre_blocks = _extract_pre_content_and_style(source)

    assert pre_blocks, "No <pre> block found in the setCowsaySentence template"

    # Look for the pre block that contains the cowsay call
    cow_pre_content = None
    for content, _style in pre_blocks:
        if 'cowsay' in content.lower() or 'say' in content.lower():
            cow_pre_content = content
            break
    # Fallback: pick the first pre block
    if cow_pre_content is None:
        cow_pre_content, _ = pre_blocks[0]

    # After the cowsay.say expression there must be a grass element.
    # The grass can be a <span> with a green style containing grass chars,
    # or plain text with grass chars that immediately follows the cowsay call.
    after_cowsay = re.split(r'\$\{cowsay\.say\(', cow_pre_content, maxsplit=1)
    assert len(after_cowsay) == 2, (
        "The cowsay.say call was not found inside the <pre> block"
    )
    tail = after_cowsay[1]  # everything after the cowsay.say expression

    # The tail must contain some green grass.
    # Accept either: a <span style="...color:green..."> or similar with grass chars,
    # or a bare grass text line without a blank line separating it.
    has_grass_span = bool(re.search(
        r'<span[^>]*style[^>]*color\s*:\s*green[^>]*>[^<]*</span>',
        tail,
        re.IGNORECASE | re.DOTALL,
    ))
    # Also accept any span with "green" in its style that contains grass-like chars
    has_green_span_with_chars = bool(re.search(
        r'<span[^>]*style[^>]*green[^>]*>[wWvV\^~\-_]',
        tail,
        re.IGNORECASE | re.DOTALL,
    ))

    assert has_grass_span or has_green_span_with_chars, (
        "No green grass span found directly after the cowsay output inside the <pre> block. "
        "Expected a <span style=\"color:green\">wWwWwWwWw</span> (or similar) immediately "
        "after ${cowsay.say(...)} with no blank line between them."
    )


# Scenario: Grass grows under the cow on the custom text page
def test_no_blank_line_between_cow_and_grass():
    """
    There must be no blank line between the last line of the cow and the grass.
    We inspect the raw template: after the cowsay.say expression the next
    non-space content must be a newline + the grass element (no empty line).
    """
    source = _load_js_source()
    pre_blocks = _extract_pre_content_and_style(source)
    assert pre_blocks, "No <pre> block found"

    cow_pre_content = None
    for content, _style in pre_blocks:
        if 'cowsay' in content.lower() or 'say' in content.lower():
            cow_pre_content = content
            break
    if cow_pre_content is None:
        cow_pre_content, _ = pre_blocks[0]

    after_cowsay = re.split(r'\$\{cowsay\.say\([^}]*\}[^}]*\}', cow_pre_content, maxsplit=1)
    if len(after_cowsay) < 2:
        # Try looser split
        after_cowsay = cow_pre_content.split('cowsay.say(', 1)
        assert len(after_cowsay) == 2, "cowsay.say not found in pre block"
        tail = after_cowsay[1]
    else:
        tail = after_cowsay[1]

    # Check there is no double-newline (blank line) before the grass element
    # A blank line would be \n\n or \n  \n
    has_blank_line_before_grass = bool(re.search(
        r'\n\s*\n\s*\n',  # two or more blank lines before grass
        tail,
    ))
    # More precisely: there must NOT be an empty line (\n followed by \n with
    # only whitespace) before the first green/grass content.
    first_green = re.search(r'green', tail, re.IGNORECASE)
    if first_green:
        before_green = tail[:first_green.start()]
        # Count consecutive newlines
        blank_line = re.search(r'\n[ \t]*\n', before_green)
        assert blank_line is None, (
            "There is a blank line between the cow's legs and the grass. "
            "The grass must appear on the very next line after the cow."
        )
    else:
        # No green found – fail with a clear message
        pytest.fail(
            "Could not find 'green' in the content after cowsay.say in the <pre> block. "
            "The grass must be coloured green and appear directly below the cow."
        )


