# Scenario: Grass grows under the cow on the quote page
def test_grass_present_for_quote_route():
    """
    The quote page (/) also calls setCowsaySentence, which means it inherits
    the same template. We verify that the single shared template includes the
    grass element, ensuring the quote page also shows the grass.
    """
    source = _load_js_source()
    # The / route must call setCowsaySentence
    assert re.search(r'setCowsaySentence\(', source), (
        "The / route must call setCowsaySentence"
    )
    # Since there is one shared template function, the grass presence is the
    # same as verified in test_pre_block_contains_grass_after_cow. Here we also
    # check the raw source for the grass element to be extra-explicit.
    pre_blocks = _extract_pre_content_and_style(source)
    found_grass = False
    for content, _style in pre_blocks:
        if re.search(r'green', content, re.IGNORECASE) and re.search(r'[wWvV\^~]', content):
            found_grass = True
            break
    assert found_grass, (
        "The shared template (used by the / quote route) must contain a green "
        "grass line inside the <pre> block."
    )


