# Grass-detection helpers
# ---------------------------------------------------------------------------

# A grass line must consist of repeated grass-like characters (w, W, v, V, ^)
# and must be at least a few characters wide.
_GRASS_CHAR_PATTERN = re.compile(r'^[wWvV\^~\-_\|/\\]+$')
_MIN_GRASS_WIDTH = 5  # must be at least this many characters wide


def _looks_like_grass(line: str) -> bool:
    """
    Return True if `line` (stripped) looks like an ASCII grass line:
    composed entirely of typical grass characters and at least MIN_GRASS_WIDTH wide.
    """
    stripped = line.strip()
    if len(stripped) < _MIN_GRASS_WIDTH:
        return False
    return bool(_GRASS_CHAR_PATTERN.match(stripped))


def _extract_pre_content_and_style(source: str) -> list[tuple[str, str]]:
    """
    Extract (content, style) pairs for every <pre ...>...</pre> block
    found in the raw JS source template, keeping the raw JS expressions
    in place so we can look for the grass span / element next to COW_OUTPUT.
    """
    # We want the raw template, not the placeholder-substituted one, because
    # the grass element may be inside the pre but outside the cowsay call.
    # Strategy: find the setCowsaySentence function body and extract <pre> content.
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)
    # Find all <pre ...> blocks (non-greedy)
    results = []
    for pre_m in re.finditer(r'<pre([^>]*)>(.*?)</pre>', template, re.DOTALL | re.IGNORECASE):
        style_attr = pre_m.group(1)
        content = pre_m.group(2)
        # Extract style value
        style_m = re.search(r'style\s*=\s*["\']([^"\']*)["\']', style_attr, re.IGNORECASE)
        style_val = style_m.group(1) if style_m else ""
        results.append((content, style_val))
    return results


