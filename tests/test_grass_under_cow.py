"""
Tests for the grass-under-the-cow feature.

Every page built by setCowsaySentence must show a line of ASCII grass
directly below the cow's legs, inside the same monospace pre block as
the cow drawing, rendered in green via an inline style.

Strategy
--------
Parse the HTML template string embedded in cowsay/src/index.js, replacing
${cowsay.say({...})} expressions with recognisable placeholders, then
inspect the surrounding markup to verify:
  - a green colour is applied (inline style)  to the grass
  - the grass is inside (or immediately adjacent to) the <pre> block
  - the grass consists of ASCII characters only (no images / SVG)
  - the cowsay.say() call is unchanged (same text param, same eye style "oO")
  - both route handlers still go through setCowsaySentence
"""

import re
import html.parser
import pytest

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

JS_PATH = "cowsay/src/index.js"

# ASCII characters commonly used for grass (must match at least one)
GRASS_CHARS = set("/\\|^vVwW'`Y,.")


# ---------------------------------------------------------------------------
# Helpers – shared extraction/parsing strategy
# ---------------------------------------------------------------------------

def _load_js_source() -> str:
    with open(JS_PATH, encoding="utf-8") as fh:
        return fh.read()


def _extract_html_template(source: str) -> str:
    """
    Return the *static* HTML generated by setCowsaySentence after replacing
    the cowsay.say(...) calls with fixed placeholders so the surrounding
    markup can be examined.
    """
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)

    # Replace ${cowsay.say({...})} with a numbered placeholder
    counter = [0]

    def _replace_cowsay(match):
        counter[0] += 1
        return f"__COW_OUTPUT_{counter[0]}__"

    template = re.sub(
        r'\$\{cowsay\.say\(\{.*?\}\)',
        _replace_cowsay,
        template,
        flags=re.DOTALL,
    )

    # Remove any remaining ${...} interpolations
    template = re.sub(r'\$\{[^}]+\}', "__INTERPOLATION__", template)
    return template


def _get_html() -> str:
    source = _load_js_source()
    return _extract_html_template(source)


class _TagParser(html.parser.HTMLParser):
    """Collects (tag, attrs_dict, inner_text) for each element."""

    def __init__(self):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []   # (tag, attrs_dict)
        self.data_chunks: list[str] = []
        self._current_data: str = ""

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def handle_data(self, data):
        self.data_chunks.append(data)


def _parse_html(html_text: str) -> _TagParser:
    parser = _TagParser()
    parser.feed(html_text)
    return parser


def _combined_inline_styles(parser: _TagParser) -> str:
    """Return all inline style attribute values concatenated (lower-cased)."""
    parts = []
    for _tag, attrs in parser.tags:
        if "style" in attrs:
            parts.append(attrs["style"].lower())
    return " ".join(parts)


