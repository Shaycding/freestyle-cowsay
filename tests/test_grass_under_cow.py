# Scenario: The grass is green and the cow is unchanged
def test_grass_is_inside_the_same_pre_block_as_the_cow():
    """
    The grass must appear inside the same <pre> block as the cow output,
    not in a separate element. This ensures the monospace alignment is shared.
    """
    source = _load_js_source()
    pre_blocks = _extract_pre_content_and_style(source)
    assert pre_blocks, "No <pre> block found in the template"

    # Find the pre block that contains the cowsay call AND a green span
    found = False
    for content, _style in pre_blocks:
        has_cow = 'cowsay' in content.lower() or 'say(' in content
        has_green = bool(re.search(r'color\s*:\s*green', content, re.IGNORECASE))
        if has_cow and has_green:
            found = True
            break

    assert found, (
        "The green grass line and the cowsay output must be inside the SAME <pre> block. "
        "No single <pre> block was found that contains both the cowsay.say call "
        "and a green colour style."
    )
