# Scenario: The cow itself is unchanged
def test_only_grass_line_added_after_cow():
    """
    The only new content after the cow drawing is the grass line.
    The grass must not replace or alter the cow output.

    We verify:
    1. The cowsay placeholder (cow drawing) is still present in the template.
    2. The green grass element is *separate* from the cow placeholder
       (so the cow drawing is not modified).
    """
    html = _get_html()

    # The first cow placeholder must still be present
    assert "__COW_OUTPUT_1__" in html, (
        "The first cow drawing placeholder is missing; "
        "the cow output must still be present in the template."
    )

    # The green grass element must exist separately from the cow placeholder
    # i.e., 'green' must appear in the template AND not be replacing the cow
    assert re.search(r'color\s*:\s*green', html, re.IGNORECASE), (
        "A green-coloured grass element must appear in the template, "
        "separate from the cow drawing."
    )

    # The grass must come AFTER the first cow placeholder in the HTML
    cow_pos = html.find("__COW_OUTPUT_1__")
    green_match = re.search(r'color\s*:\s*green', html, re.IGNORECASE)
    assert green_match, "No green element found in the template"
    green_pos = green_match.start()
    assert green_pos > cow_pos, (
        "The grass line must appear AFTER the cow drawing in the HTML, "
        "not before it."
    )


# Scenario: The cow itself is unchanged
def test_grass_line_is_at_least_as_wide_as_typical_cow():
    """
    The grass line must be at least as wide as the cow drawing.
    A standard cowsay cow is about 40 characters wide.
    We require the grass to be at least 10 characters wide (a conservative
    lower bound that a single grass character repeated would meet).
    """
    html = _get_html()

    # Find the grass content: either inside a span with green style,
    # or a repeated grass character run
    span_match = re.search(
        r'<span[^>]*style\s*=\s*["\'][^"\']*color\s*:\s*'
        r'(?:green|#[0-9a-fA-F]{3,6})[^"\']*["\'][^>]*>(.*?)</span>',
        html,
        re.IGNORECASE | re.DOTALL,
    )
    if span_match:
        grass_content = span_match.group(1)
        assert len(grass_content.strip()) >= 10, (
            f"Grass line is too short ({len(grass_content.strip())} chars); "
            "it must be at least as wide as the cow drawing (>= 10 chars)."
        )
    else:
        grass_pattern = re.compile(r'[/\\|^vVwW\'`Y,.]{4,}')
        m = grass_pattern.search(html)
        assert m, "No grass line found in template to check width"
        assert len(m.group(0)) >= 10, (
            f"Grass line is too short ({len(m.group(0))} chars); "
            "it must be at least as wide as the cow drawing (>= 10 chars)."
        )
