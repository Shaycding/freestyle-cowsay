# Scenario: The grass is green and the cow is unchanged
def test_grass_characters_are_grass_like():
    """
    The grass line must consist of ASCII grass characters such as w, W, v, V,
    ^ or similar. We look for these characters near the green colour in the
    template.
    """
    source = _load_js_source()
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "setCowsaySentence template not found"
    template = m.group(1)

    # Find the green element and check its content for grass chars
    green_span = re.search(
        r'<span[^>]*color\s*:\s*green[^>]*>(.*?)</span>',
        template,
        re.IGNORECASE | re.DOTALL,
    )
    assert green_span, (
        "No <span style='color:green'>...</span> (or similar) found for the grass."
    )
    grass_content = green_span.group(1)
    # Must contain at least one grass character
    assert re.search(r'[wWvV\^~]', grass_content), (
        f"The green span does not contain grass-like characters (w/W/v/V/^/~). "
        f"Found: {grass_content!r}"
    )


