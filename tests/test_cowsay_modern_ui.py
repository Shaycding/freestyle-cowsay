# Scenario: Custom text is shown in the modern card
def test_cow_is_drawn_in_monospace_font():
    """
    The element that wraps the cow drawing must use a monospace font so that
    the ASCII art lines up correctly. This must be expressed in an inline style
    or as the native font of a <pre> element (which browsers render monospace
    by default), but the spec requires explicit styling here.
    We accept either:
      - a <pre> element (which has monospace semantics by default), OR
      - an element with font-family containing 'monospace' in its inline style.
    """
    html = _get_html()
    parser = _parse_html(html)

    has_pre = any(tag == "pre" for tag, _ in parser.tags)
    styles = _combined_inline_styles(parser)
    has_monospace_style = "monospace" in styles

    assert has_pre or has_monospace_style, (
        "The cow drawing must be in a <pre> element or have font-family:monospace "
        "in an inline style"
    )


