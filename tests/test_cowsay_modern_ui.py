# Scenario: The page fits a phone screen
def test_page_has_viewport_meta_tag():
    """
    The page must include a viewport meta tag so that it renders correctly
    on phone screens (375 px wide).
    """
    html = _get_html()
    parser = _parse_html(html)

    viewport_tags = [
        attrs for tag, attrs in parser.tags
        if tag == "meta" and attrs.get("name", "").lower() == "viewport"
    ]
    assert viewport_tags, "Missing <meta name='viewport'> tag"

    content = viewport_tags[0].get("content", "").lower()
    assert "width=device-width" in content, (
        "Viewport meta must include width=device-width for phone screens"
    )


# Scenario: The page fits a phone screen
def test_card_constrained_width_for_phone():
    """
    The card must have a max-width so it doesn't overflow a 375 px screen,
    or the layout must use a responsive unit (%, vw) rather than a fixed
    pixel width that exceeds phone screen width.
    Acceptable: max-width in any inline style, or width expressed as %.
    """
    html = _get_html()
    parser = _parse_html(html)
    styles = _combined_inline_styles(parser)

    has_max_width = "max-width" in styles
    has_width_percent = re.search(r'width\s*:\s*\d+%', styles) is not None
    has_width_100 = "width: 100%" in styles or "width:100%" in styles

    assert has_max_width or has_width_percent or has_width_100, (
        "The card must have max-width or a percentage-based width "
        "so it fits a 375 px phone screen"
    )


# Scenario: The page fits a phone screen
def test_cow_drawing_scrolls_inside_card():
    """
    The cow drawing must scroll inside the card rather than breaking the layout
    on narrow screens. Acceptable signals in inline style:
      - overflow-x: auto  or  overflow: auto  or  overflow: scroll
      - white-space: pre  (keeps pre formatting while allowing card overflow)
    A bare <pre> element provides scrolling by default in most browsers, so
    we also accept that as sufficient.
    """
    html = _get_html()
    parser = _parse_html(html)
    styles = _combined_inline_styles(parser)

    has_overflow = re.search(r'overflow(-x)?\s*:\s*(auto|scroll)', styles) is not None
    has_pre = any(tag == "pre" for tag, _ in parser.tags)

    assert has_overflow or has_pre, (
        "The cow drawing must be in a <pre> or have overflow:auto/scroll "
        "so it scrolls inside the card on narrow screens"
    )


