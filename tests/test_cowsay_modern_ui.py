def test_page_has_cow_say_header():
    """
    The page must show a visible 'Cow Say' header (h1 or similar heading).
    """
    source = _load_js_source()
    html = _extract_html_template(source)

    # "Cow Say" must appear as visible text (not just in <title>)
    # We look for it in the body portion after </head>
    body_part = html
    head_end = html.lower().find("</head>")
    if head_end != -1:
        body_part = html[head_end:]

    assert "Cow Say" in body_part, (
        "The body must contain a 'Cow Say' heading visible to the user"
    )


