# Scenario: Custom text is shown in the modern card
def test_no_external_stylesheets_or_scripts():
    """
    The page must load no external stylesheets, fonts or scripts.
    All styling is inline.
    """
    source = _load_js_source()
    html = _extract_html_template(source)
    parser = _parse_html(html)

    for tag, attrs in parser.tags:
        # No <link rel="stylesheet"> allowed
        if tag == "link":
            rel = attrs.get("rel", "").lower()
            assert "stylesheet" not in rel, (
                f"Found an external stylesheet link: {attrs}"
            )
            # No Google Fonts / external font links
            href = attrs.get("href", "")
            assert not href.startswith("http"), (
                f"Found an external <link> with remote href: {href}"
            )

        # No <script src="..."> allowed
        if tag == "script":
            assert "src" not in attrs, (
                f"Found an external script: {attrs}"
            )


