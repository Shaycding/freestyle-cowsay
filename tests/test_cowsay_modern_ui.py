"""
Tests for the modern look of the cowsay page.

These tests parse the HTML template embedded in cowsay/src/index.js and verify
that the setCowsaySentence function produces markup consistent with the
modern-look specification. No running server or Node.js is required.

Strategy
--------
1. Extract the raw HTML template string from the JS source (substituting a
   known placeholder for the cowsay output so we can inspect the surrounding
   structure).
2. Parse the HTML with html.parser and apply CSS-aware assertions that check
   for the required style attributes / element structure.
"""

import re
import html.parser
import pytest


# ---------------------------------------------------------------------------
# Helpers – extract the HTML produced by setCowsaySentence
# ---------------------------------------------------------------------------

JS_PATH = "cowsay/src/index.js"


def _load_js_source() -> str:
    with open(JS_PATH, encoding="utf-8") as fh:
        return fh.read()


def _extract_html_template(source: str) -> str:
    """
    Return the *static* HTML generated by setCowsaySentence after replacing
    the cowsay.say(...) call with a fixed placeholder so the surrounding
    markup can be examined.
    """
    # Locate the template literal returned from setCowsaySentence.
    # The function body is:   const setCowsaySentence = (text) => { return `...`; }
    # We find the opening back-tick of the return statement and match its
    # closing back-tick (the one not preceded by a \).
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        # Fallback: grab everything between the first ` after `return ` inside
        # the function and the last ` before the closing `}` of the function.
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)

    # Replace the embedded JS expression ${cowsay.say({...})} with a
    # recognisable placeholder that survives HTML parsing.
    template = re.sub(r'\$\{cowsay\.say\(\{[^}]*\}[^}]*\}\)', "__COW_OUTPUT__", template, flags=re.DOTALL)

    # Remove any remaining ${...} interpolations (like ${text}) that would
    # break the HTML parser; replace them with a placeholder too.
    template = re.sub(r'\$\{[^}]+\}', "__INTERPOLATION__", template)

    return template


class _CollectingParser(html.parser.HTMLParser):
    """Simple parser that records tags and their attrs in order."""

    def __init__(self):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []   # (tag, attrs_dict)
        self.data_chunks: list[str] = []

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def handle_data(self, data):
        self.data_chunks.append(data)


def _parse_html(html_text: str) -> _CollectingParser:
    parser = _CollectingParser()
    parser.feed(html_text)
    return parser


def _combined_inline_styles(parser: _CollectingParser) -> str:
    """Return all inline style attribute values concatenated (lower-cased)."""
    parts = []
    for _tag, attrs in parser.tags:
        if "style" in attrs:
            parts.append(attrs["style"].lower())
    return " ".join(parts)


def _get_html() -> str:
    source = _load_js_source()
    return _extract_html_template(source)


def _get_parser() -> _CollectingParser:
    return _parse_html(_get_html())


