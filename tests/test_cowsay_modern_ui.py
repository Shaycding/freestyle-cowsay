def test_same_template_used_for_all_routes():
    """
    Both / and /:text routes call setCowsaySentence and return its output,
    so they automatically share the same layout. We verify that both route
    handlers reference setCowsaySentence (ensuring neither route bypasses it
    with a different template).
    """
    source = _load_js_source()

    # Count how many times setCowsaySentence is called (not its definition)
    calls = re.findall(r'setCowsaySentence\(', source)
    # definition + at least 2 call sites (one per route, / may have multiple
    # due to error-handling branches)
    assert len(calls) >= 3, (
        f"Expected at least 3 references to setCowsaySentence "
        f"(1 definition + at least 2 route call sites), found {len(calls)}"
    )


