"""
Tests for the "Feed the cow" button feature.

Every Cow Say page must show a button labelled "Feed the cow".
Clicking it makes the first cow say "Thank you for the food!".
After feeding, the green grass and the second answering cow are still shown.

Strategy
--------
Parse the HTML template string embedded in cowsay/src/index.js, replacing
${cowsay.say({...})} expressions with recognisable placeholders, then
inspect the surrounding markup to verify the presence and behaviour of the
"Feed the cow" button.

For the click / interactive behaviour, we verify:
  - A button with the label "Feed the cow" is present in the static HTML.
  - The inline script / JavaScript embedded in the page handles the click so
    that it makes the first cow's <pre> element (or container) show
    "Thank you for the food!".
  - The green grass and the second-cow output remain present in the DOM
    (i.e. they are not removed by the feed action).
"""

import re
import html.parser
import pytest

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

JS_PATH = "cowsay/src/index.js"
FEED_BUTTON_LABEL = "Feed the cow"
THANK_YOU_TEXT = "Thank you for the food!"
SECOND_COW_ANSWERS = [
    "Moo, so true!",
    "I was just thinking that.",
    "Deep. Very deep.",
]


# ---------------------------------------------------------------------------
# Helpers – same extraction strategy as the rest of the test suite
# ---------------------------------------------------------------------------

def _load_js_source() -> str:
    with open(JS_PATH, encoding="utf-8") as fh:
        return fh.read()


def _extract_html_template(source: str) -> str:
    """
    Return the *static* HTML generated by setCowsaySentence, replacing
    all ${cowsay.say({...})} expressions with numbered placeholders and
    removing other ${...} interpolations.
    """
    m = re.search(
        r'const\s+setCowsaySentence\s*=\s*\(text\)\s*=>\s*\{[^`]*`(.*)`\s*;?\s*\}',
        source,
        re.DOTALL,
    )
    if not m:
        m = re.search(
            r'const\s+setCowsaySentence\s*=.*?return\s+`(.*)`',
            source,
            re.DOTALL,
        )
    assert m, "Could not locate the template literal in setCowsaySentence"
    template = m.group(1)

    # Replace every ${cowsay.say({...})} expression with a numbered placeholder
    counter = [0]

    def _replace_cowsay(match):
        counter[0] += 1
        return f"__COW_OUTPUT_{counter[0]}__"

    template = re.sub(
        r'\$\{cowsay\.say\(\{.*?\}\)',
        _replace_cowsay,
        template,
        flags=re.DOTALL,
    )

    # Remove any remaining ${...} interpolations (e.g. ${text})
    template = re.sub(r'\$\{[^}]+\}', "__INTERPOLATION__", template)
    return template


def _get_html() -> str:
    source = _load_js_source()
    return _extract_html_template(source)


class _CollectingParser(html.parser.HTMLParser):
    """Simple parser that records tags, their attrs, and text data."""

    def __init__(self):
        super().__init__()
        self.tags: list[tuple[str, dict]] = []   # (tag, attrs_dict)
        self.data_chunks: list[str] = []

    def handle_starttag(self, tag, attrs):
        self.tags.append((tag, dict(attrs)))

    def handle_data(self, data):
        self.data_chunks.append(data)


def _parse_html(html_text: str) -> _CollectingParser:
    parser = _CollectingParser()
    parser.feed(html_text)
    return parser


