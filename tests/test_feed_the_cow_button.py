# Scenario: Grass and the second cow stay after feeding
def test_green_grass_still_in_template_after_feed():
    """
    After feeding the cow, the green grass under the first cow must still
    be shown.  We verify that the green grass span/element is present in
    the template and that the feed action does not alter it.
    """
    html = _get_html()

    # The grass must be marked with a green colour (as established by the
    # existing grass-under-cow feature)
    has_green_style = "color: green" in html or "color:green" in html
    has_green_span = bool(re.search(r'<span[^>]+color\s*:\s*green', html, re.IGNORECASE))

    assert has_green_style or has_green_span, (
        "The green grass must still be present in the HTML template "
        "after the feed action. The grass must not be removed when the cow is fed."
    )


