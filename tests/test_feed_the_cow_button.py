# Scenario: The quote page shows the Feed the cow button
def test_feed_button_present_in_template():
    """
    The HTML template returned by setCowsaySentence must contain a <button>
    element whose visible label is "Feed the cow".  This guarantees the button
    appears on both the quote page (/) and custom text pages (/:text).
    """
    html = _get_html()
    parser = _parse_html(html)

    # Collect all <button> tags
    buttons = [(tag, attrs) for tag, attrs in parser.tags if tag == "button"]
    assert buttons, "No <button> element found in the HTML template"

    # The full rendered HTML (including text nodes) must contain the label
    assert FEED_BUTTON_LABEL in html, (
        f'No button labelled "{FEED_BUTTON_LABEL}" found in the HTML template. '
        "Every Cow Say page must show a 'Feed the cow' button."
    )


