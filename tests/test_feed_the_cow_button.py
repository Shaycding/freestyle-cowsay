# Scenario: Feeding the cow makes the first cow say thank you
def test_thank_you_text_in_page_script():
    """
    Clicking "Feed the cow" must make the first cow say "Thank you for the food!".
    Since this is a server-rendered page with no separate JS bundle, the
    behaviour must be implemented by inline JavaScript embedded in the template.
    The string "Thank you for the food!" must appear in the JS source of the
    page (inside the setCowsaySentence template literal or in an inline <script>
    block within it) so the client-side handler can use it.
    """
    html = _get_html()
    assert THANK_YOU_TEXT in html, (
        f'The text "{THANK_YOU_TEXT}" must be present in the page HTML/script '
        "so that clicking 'Feed the cow' can make the first cow display it."
    )


# Scenario: Feeding the cow makes the first cow say thank you
def test_first_cow_container_has_id_or_hook_for_feed_action():
    """
    The inline JavaScript that handles the "Feed the cow" click must be able
    to target the first cow's output container.  This requires either:
      - The first <pre> / cow container has an id attribute, OR
      - There is an inline onclick handler on the button referencing the
        "Thank you for the food!" text, OR
      - A <script> block in the template contains "Thank you for the food!".
    At least one of these must be present.
    """
    html = _get_html()
    parser = _parse_html(html)

    # Check for an element with an id that can be targeted by the button handler
    elements_with_id = [attrs for _, attrs in parser.tags if "id" in attrs]

    # Check for onclick on a button that references the thank-you text
    buttons = [(tag, attrs) for tag, attrs in parser.tags if tag == "button"]
    button_has_onclick = any("onclick" in attrs for _, attrs in buttons)

    # Check that the thank-you string itself is embedded somewhere in the page
    thank_you_in_page = THANK_YOU_TEXT in html

    assert elements_with_id or button_has_onclick or thank_you_in_page, (
        "The page must provide a way for the 'Feed the cow' button to update "
        "the first cow's text to 'Thank you for the food!'. "
        "Expected either: an id on the first cow container, an onclick on the "
        "button, or the thank-you string embedded in a script block."
    )


